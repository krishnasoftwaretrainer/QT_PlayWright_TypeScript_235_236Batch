let day:string="GEFMGNME";

switch(day.toLowerCase())
{
    case "monday":
        {
            console.log("Today Monday");
            break;
        }
        case "tuesday":
        {
            console.log("Today tuesday");
            break;
        }
        case "wednessday":
        {
            console.log("Today wednessday");
            break;
        }
        case "thursday":
        {
            console.log("Today thursday");
            break;
        }
        default:
            {
                console.log("Not a week day");
            }
}